# Fixture coverage audit

The OpenAPI specs and the hand-written Rust structs are two sources of
truth. The recorded e2e fixtures under `fixtures/<domain>/` are a third
— and arguably the most authoritative — source: what the bunny.net API
*actually* sends today.

This report runs `audit-fixture-coverage.sh` over every fixture that maps
cleanly to a struct hoppy uses, and pairs the result with the spec when
one is available. Three pair-wise diffs surface different problem
classes:

| Diff | Interpretation |
|---|---|
| fixture − struct | **The real gap**: a field the API sends now that hoppy silently drops. |
| struct − fixture | A field hoppy models but the API didn't send in this recording. Either server-omitted (default), write-only, or a stale struct field. |
| fixture − spec | **Spec lag**: the API ships a field its own OpenAPI doc doesn't list yet. Worth filing upstream. |
| spec − fixture | A documented field the server omitted from this recording (often defaults to absent). |

Generated by `hoppy-knowledgebase/scripts/run-fixture-coverage-audit.sh`.

HDR

echo "$TUPLES" | while IFS='|' read -r title fixture prefix struct_file struct_name spec schema; do
    [ -n "$title" ] || continue
    if [ "$spec" = "-" ] || [ "$schema" = "-" ]; then
        "$SCRIPT" --fixture "$fixture" --jq-prefix "$prefix" \
                  --struct-file "$struct_file" --struct-name "$struct_name" \
                  --title "$title" 2>/dev/null || {
            echo "## $title"; echo
            echo "> **TODO:** audit failed — likely struct or fixture missing."
            echo
            continue
        }
    else
        "$SCRIPT" --fixture "$fixture" --jq-prefix "$prefix" \
                  --struct-file "$struct_file" --struct-name "$struct_name" \
                  --spec "$spec" --schema "$schema" \
                  --title "$title" 2>/dev/null || {
            echo "## $title"; echo
            echo "> **TODO:** audit failed — likely struct or fixture missing."
            echo
            continue
        }
    fi
    echo
done

cat <<'FOOT'

## Takeaways

- **Pull zone fixtures confirm the spec count**: each recorded
