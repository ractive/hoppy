  `PullZoneModel` declares. There is no "the spec over-states what the
  API returns" effect for pull zones; the 110-field struct gap is real
  on every recording.
- **Shield zone fixture is wrapped in `data`**: handled here via the
  `.data` jq prefix. The bare struct/fixture comparison still suggests
  most "casing mismatches" reported in the spec audit are real (the
  Shield API uses camelCase end-to-end).
- **Container app fixtures have no spec to diff against**, matching
